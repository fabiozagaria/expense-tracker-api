-- Schema iniziale PostgreSQL (database Neon e sviluppo locale).
-- Corrisponde alle entità JPA: Hibernate lo controlla all'avvio con ddl-auto=validate.
-- Gli istanti (Instant) sono timestamptz; le categorie restano testo con un vincolo CHECK
-- (EnumType.STRING), così aggiungere un valore è una migrazione che cambia solo il vincolo.

CREATE TABLE users (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          varchar(255) NOT NULL,
    email_verified boolean      NOT NULL,
    password       varchar(255) NOT NULL,
    role           varchar(20)  NOT NULL CHECK (role IN ('ADMIN', 'USER')),
    username       varchar(20)  NOT NULL
);

-- MySQL confrontava username ed email senza distinguere maiuscole e minuscole (collation *_ci);
-- PostgreSQL le distingue. Gli indici su lower() impediscono "Fabio" e "fabio" come account diversi,
-- e UserRepository cerca con lower() per usarli.
CREATE UNIQUE INDEX ux_users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));

CREATE TABLE refresh (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at  timestamp(6) with time zone NOT NULL,
    expire_at  timestamp(6) with time zone NOT NULL,
    revoke_at  timestamp(6) with time zone,
    token_hash varchar(255) NOT NULL UNIQUE,
    user_id    bigint       NOT NULL REFERENCES users (id)
);
CREATE INDEX ix_refresh_user_id ON refresh (user_id);

CREATE TABLE verification_tokens (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at  timestamp(6) with time zone NOT NULL,
    expire_at  timestamp(6) with time zone NOT NULL,
    token_hash varchar(255) NOT NULL UNIQUE,
    used_at    timestamp(6) with time zone,
    user_id    bigint       NOT NULL REFERENCES users (id)
);
CREATE INDEX ix_verification_tokens_user_id ON verification_tokens (user_id);

CREATE TABLE password_reset_tokens (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at  timestamp(6) with time zone NOT NULL,
    expire_at  timestamp(6) with time zone NOT NULL,
    token_hash varchar(255) NOT NULL UNIQUE,
    used_at    timestamp(6) with time zone,
    user_id    bigint       NOT NULL REFERENCES users (id)
);
CREATE INDEX ix_password_reset_tokens_user_id ON password_reset_tokens (user_id);

CREATE TABLE expenses (
    id_expenses bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount      numeric(38, 2) NOT NULL,
    category    varchar(20)    NOT NULL CHECK (category IN ('bills', 'car', 'gifts', 'groceries', 'health',
                    'housing', 'installments', 'leisure', 'loan', 'other', 'transport')),
    date        date           NOT NULL,
    description varchar(30),
    title       varchar(15)    NOT NULL,
    user_id     bigint         NOT NULL REFERENCES users (id)
);
CREATE INDEX ix_expenses_user_id ON expenses (user_id);

CREATE TABLE incomes (
    id_incomes  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount      numeric(38, 2) NOT NULL,
    category    varchar(20)    NOT NULL CHECK (category IN ('bonus', 'freelance', 'gift', 'investment', 'other',
                    'refund', 'rental', 'salary')),
    date        date           NOT NULL,
    description varchar(30),
    title       varchar(15)    NOT NULL,
    user_id     bigint         NOT NULL REFERENCES users (id)
);
CREATE INDEX ix_incomes_user_id ON incomes (user_id);
